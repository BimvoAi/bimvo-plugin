export type CopyKey = keyof typeof pt;
export type StoreText = (
  key: CopyKey,
  vars?: Record<string, string | number>,
) => string;

export function storeText(locale: string): StoreText {
  const messages = locale === 'en' ? en : locale === 'es' ? es : pt;
  return (key, vars = {}) =>
    messages[key].replace(/\{(\w+)\}/g, (_, name: string) =>
      String(vars[name] ?? ''),
    );
}
